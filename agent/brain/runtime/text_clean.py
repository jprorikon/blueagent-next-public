"""回覆文字的清洗（2026-10-29 owner：回信带 # 数字、TTS 念数字、假贴图）

三種要清掉的東西：

1. **`#112（いま）`** —— 那是**畫面用的標記**（歷史上帶編號的那些行），
   不是話。模型有時會照抄進回覆 ⇒ TTS 會念「一一二」。
2. **`[[stamp_in:…]]`／`[[stamp_out:…]]`** —— 貼圖的標籤（主人送的／她自己回過的，
   只給模型看），不該被回抄。
3. **`（スタンプ：えへへ）`** —— 她有時會在正文寫這種**假貼圖**；
   真正的貼圖走 `sticker` 幀（畫面上的圖），正文寫字串既不顯示圖也不該被念。

⚠️ 只清這些，**不做任何「順便美化」**（不改她的語氣、不刪正常句子）。
"""
from __future__ import annotations

import re

#: 「多久前」的寫法（`domain/time.human_age` 會出的那幾種，加上模型自己編的「いま」）
_AGE = (r"(?:いま|さっき|\d+\s*(?:分|時間|日)前|昨日\s*\d{1,2}:\d{2}"
        r"|\d{1,2}月\d{1,2}日\s*\d{1,2}:\d{2}|\d{4}-\d{2}-\d{2}\s*\d{1,2}:\d{2})")
#: `#112（いま）` / `#118(3 分前)` ⇒ 連號碼帶括號一起刪。
#: ⚠️ **只認「#號碼＋時間括號」這個形狀**（複檢 2026-10-29）：一般的 `issue #123`、`ランキング#1`、
#: `#3（重要）` 是她正常會寫的話（她也幫主人做事），不能刪。
_MARKER_RE = re.compile(rf"[#＃]\s*\d+\s*(?:（\s*{_AGE}\s*）|\(\s*{_AGE}\s*\))")
#: 沒帶時間的舊標記：只認**行首**、號碼後面**直接接正文**的（以前歷史行是 `#12` 緊貼正文）；
#: `#123 は直した`（中間有空白）、`#3（重要）`（後面是括號）當成一般的話留著。
_BARE_MARKER_RE = re.compile(r"(?m)^[ \t]*[#＃]\d+(?=[^\x00-\x7f（【「『]|$)")
#: 貼圖標籤（主人送的 `stamp_in`／她自己回過的 `stamp_out`）
_STAMP_TAG_RE = re.compile(r"\[\[stamp_(?:in|out):[^\]]*\]\]")
#: **內部標記**〔私記〕（她自己那層記憶的前綴，只給模型看）
#: ⚠️ 2026-11-03 實測：nori 把它照抄進回覆 4 次（「我记得，〔私記〕ノリ「…」3/4…」）
#: ⇒ 定稿時一律剝掉；標記後面的空白也一起收。
_PRIVATE_MARK_RE = re.compile(r"〔私記〕\s*")
#: 動作標籤（她在回覆開頭標的 `[[motion:greet]]`；串流時已經抽走，這裡是定稿的保險）
MOTION_TAG_RE = re.compile(r"\[\[motion:([a-z_]*)\]\]")
#: 假的貼圖字串（正文裡寫出來的，不是真的送圖）
#: ⚠️ **不要順便吃掉句子結尾的括號**（她正常寫「これはうん（真面目に）」是合法的）
#: ⇒ 只刪掉貼圖字串本身；若因此留下**孤立**的收尾括號，再另外收掉。
#: ⚠️ **沒收尾括號時不能一路吃到句尾**（複檢 2026-10-29：`（スタンプ：えへへ それでね…` 整句不見）
#: ⇒ 有收尾括號：只認 30 字以內、中間沒有別的括號；沒有：只刪到第一個空白／句號為止。
_FAKE_STICKER_RE = re.compile(r"[（(]\s*スタンプ(?:を?返す|：|:)"
                              r"(?:[^（(）)\n]{0,30}[）)]|[^（(）)。！？!?\s]{0,20})")
#: 孤立在句尾的收尾括號（前面已經沒有開括號了）
_DANGLING_CLOSE_RE = re.compile(r"[）)]\s*$")
#: **整串**只剩空白／括號 ⇒ 沒有可唸的內容。
#: ⚠️ 以前寫成 `^[開括號]|[收括號]+$`（優先序錯）⇒ 凡是以「「」「（」「【」開頭的回覆都被整句清空
#: （複檢 2026-10-29：`「おはよう」って…`、`（小声で）うん` 全變空字串）。
_BRACKET_ONLY = re.compile(r"^[\s（(【\[「『）)】\]」』]+$")


def clean_reply(text: object) -> str:
    """把「不是話」的部分去掉，只留真正要顯示／要唸的東西。"""
    out = str(text or "").strip()
    if not out:
        return ""
    out = _MARKER_RE.sub("", out)
    out = _BARE_MARKER_RE.sub("", out)
    out = _STAMP_TAG_RE.sub("", out)
    out = _PRIVATE_MARK_RE.sub("", out)          # 〔私記〕只給模型看，不進回覆
    out = MOTION_TAG_RE.sub("", out)
    out = _FAKE_STICKER_RE.sub("", out)
    out = out.strip()
    # 貼圖字串被刪掉後可能留下**孤立**的收尾括號（`…よね。（スタンプを返す` ⇒ `…よね。）`）
    # ⇒ 只有在「這句裡沒有任何開括號」時才收掉它（正常句子的括號配對不受影響）。
    if out and _DANGLING_CLOSE_RE.search(out) and "（" not in out and "(" not in out:
        out = _DANGLING_CLOSE_RE.sub("", out).strip()
    if not out or _BRACKET_ONLY.match(out):
        return ""
    return out
