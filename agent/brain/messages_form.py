"""返事の「形」段（`[[form]]`）：渠道ごとの長さ・書式の縛り。

owner 2026-11-11：App と声（TTS）は短く、Discord の文字だけは縛らない。通話は `[[call]]` が同じ役。

**App のグループ会話は別の形**（2026-11-17，M5 `GROUP-SELF-CHAT-20261108.md` §10）：
以前はグループも 1:1 と同じ「全体で 1〜3 文」⇒ 群聊の分布表（2026-11-15）で発言の字数の最頻値が
**41 字以上**、§10 の判定は「最頻値が 6〜10 字」。グループで毎回三文の段落を出すのは人の雑談の形ではない
（相づち・ツッコミ・一言の感想が大半）。⇒ ふだんは一文・10 字前後、聞かれた／説明を頼まれたときだけ伸ばす。
字数で切り捨てる後処理はしない：切ると本人の記録（thread）と画面がずれる。形は本人に言う。
"""

from __future__ import annotations

FORM_BLOCK = ("[[form]]\n返事はそのまま画面と声に出る。最初の一文は短く（15 文字以内）、全体で 1〜3 文"
              "（長い説明が要る回だけ少し伸ばす）。箇条書き・見出し・Markdown・絵文字・記号（* _ ` # |）は使わない。"
              "数字と単位は読み上げやすい形で。\n[[/form]]")

GROUP_FORM_BLOCK = ("[[form]]\nここはグループの雑談。返事はそのまま画面に出る。"
                    "ふだんは**ひと言**で返す（10 文字前後、一文）——相づち・ツッコミ・短い感想で十分。"
                    "質問されたとき、説明や段取りを頼まれたときだけ 2〜3 文まで。"
                    "全員に向けた長い報告・前の話のまとめ・相手の発言の言い直しはしない。"
                    "箇条書き・見出し・Markdown・絵文字・記号（* _ ` # |）は使わない。\n[[/form]]")


def form_block(meta) -> str:
    """この回に付ける `[[form]]` 段（付けないときは空文字）。"""
    channel = str(meta.get("channel") or "")
    if not channel or channel == "discord" or meta.get("in_call"):
        return ""
    if channel == "app" and meta.get("group"):
        return GROUP_FORM_BLOCK
    return FORM_BLOCK
